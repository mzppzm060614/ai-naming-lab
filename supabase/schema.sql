-- ============================================================
-- 阶段3 Supabase 建表 SQL
-- 用法：Supabase 后台 → SQL Editor → New query → 粘贴本文件 → Run
-- 表名 / 字段名与老师参考 SQL 保持一致：
--   name_history(user_requirement, name_result, model_name, created_at)
-- ============================================================

create table if not exists name_history (
  id                bigint generated by default as identity primary key,
  user_requirement  text        not null,
  name_result       text        not null,
  model_name        text        not null,
  created_at        timestamp with time zone default now()
);

-- 按时间倒序查历史时用的索引
create index if not exists name_history_created_at_idx
  on name_history (created_at desc);

-- ------------------------------------------------------------
-- RLS（行级安全）说明：
-- 调试阶段：可以先在 Supabase 后台 Table → Authentication 里临时关闭 RLS，
--           或暂时不加 policy，方便接口先跑通。
-- 正式上线：不要长期关闭 RLS，也不要给 anon 角色无条件全表权限。
--   方案 A（本项目采用）：数据库访问只放在服务端接口，使用 service_role
--           密钥（service_role 绕过 RLS），前端浏览器不直连数据库；
--   方案 B：若必须用 anon 密钥让前端直连，按最小权限写 policy，
--           例如只允许插入、只能读取自己的记录，不要用 using (true) 全开。
-- ------------------------------------------------------------

alter table name_history enable row level security;

-- 阶段2 服务端用 anon 密钥调试，临时开放读取和插入；上线前按上面说明收紧
create policy "anon 可读取起名历史"
  on name_history
  for select
  to anon
  using (true);

create policy "anon 可插入起名记录"
  on name_history
  for insert
  to anon
  with check (true);
